/* Keep the stdout adapter independent of the HAL's formatted-I/O library.
 * Avalon JTAG UART control[31:16] is the number of writable FIFO entries.
 * Wait a bounded time for space, then latch "no host" and drop characters at
 * full speed until space reappears, so a detached terminal cannot deadlock
 * the program. */
#define UART_WRITE_TIMEOUT_TICKS 100000000u /* ~1 s at 100 MHz */
#define UART_ABSENT_STRIKES      2u

static uint32_t uart_timeouts = 0u;
static uint32_t uart_dropped_chars = 0u;

static void uart_putc(char c)
{
    uint32_t start;

    if (uart_timeouts >= UART_ABSENT_STRIKES) {
        if ((jtag_uart[1] >> 16) == 0u) {
            ++uart_dropped_chars;
            return;
        }
        uart_timeouts = 0u;
    }

    start = clock_ticks32();
    while ((jtag_uart[1] >> 16) == 0u) {
        if ((uint32_t)(clock_ticks32() - start) > UART_WRITE_TIMEOUT_TICKS) {
            ++uart_timeouts;
            ++uart_dropped_chars;
            return;
        }
    }
    uart_timeouts = 0u;
    jtag_uart[0] = (uint32_t)(uint8_t)c;
}

static void uart_puts(const char *text)
{
    while (*text != '\0')
        uart_putc(*text++);
}

static int uart_putc_nb(char c)
{
    if ((jtag_uart[1] >> 16) == 0u)
        return 0;
    jtag_uart[0] = (uint32_t)(uint8_t)c;
    return 1;
}

static void uart_puts_nb(const char *text)
{
    while (*text != '\0') {
        if (!uart_putc_nb(*text++))
            return;
    }
}

static void uart_hex16(uint16_t value)
{
    static const char digits[] = "0123456789abcdef";
    uint32_t shift;
    for (shift = 12u; ; shift -= 4u) {
        uart_putc(digits[(value >> shift) & 0xfu]);
        if (shift == 0u)
            break;
    }
}

static void uart_hex32(uint32_t value)
{
    uart_hex16((uint16_t)(value >> 16));
    uart_hex16((uint16_t)value);
}

static void uart_hex8(uint8_t value)
{
    static const char digits[] = "0123456789abcdef";
    uart_putc(digits[(value >> 4) & 0xfu]);
    uart_putc(digits[value & 0xfu]);
}

static void uart_dec32(uint32_t value)
{
    char digits[10];
    uint32_t count = 0u;
    if (value == 0u) {
        uart_putc('0');
        return;
    }
    while (value != 0u) {
        digits[count++] = (char)('0' + (value % 10u));
        value /= 10u;
    }
    while (count != 0u)
        uart_putc(digits[--count]);
}

static void uart_dec32_nb(uint32_t value)
{
    char digits[10];
    uint32_t count = 0u;
    if (value == 0u) {
        (void)uart_putc_nb('0');
        return;
    }
    while (value != 0u) {
        digits[count++] = (char)('0' + (value % 10u));
        value /= 10u;
    }
    while (count != 0u) {
        if (!uart_putc_nb(digits[--count]))
            return;
    }
}

/* Print an IEEE binary16 as a signed fixed-point decimal with three places,
 * using integer arithmetic only (no soft-float, no printf).
 *   E != 0 : value = (1024 + M) * 2^(E - 25)
 *   E == 0 : value = M * 2^-24
 * The ResNet-8 logit range is roughly [-27, +18], so the shift is always to
 * the right and a 32-bit intermediate cannot overflow.  Out-of-range or
 * non-finite encodings are reported literally instead of being decoded. */
static void uart_half(uint16_t h)
{
    uint32_t sign = (uint32_t)(h >> 15);
    uint32_t exponent = (uint32_t)((h >> 10) & 0x1fu);
    uint32_t mantissa = (uint32_t)(h & 0x3ffu);
    uint32_t numerator;
    int32_t shift;
    uint32_t milli;

    if (exponent == 0x1fu) {
        uart_puts(mantissa ? "nan" : (sign ? "-inf" : "+inf"));
        return;
    }
    if (exponent == 0u) {
        numerator = mantissa;
        shift = -24;
    } else {
        numerator = 1024u + mantissa;
        shift = (int32_t)exponent - 25;
    }

    if (shift >= 0) {
        if (shift > 12) {              /* would overflow / absurd magnitude */
            uart_puts(sign ? "-huge" : "+huge");
            return;
        }
        milli = (numerator * 1000u) << (uint32_t)shift;
    } else {
        uint32_t s = (uint32_t)(-shift);
        if (s >= 31u) {
            milli = 0u;
        } else {
            milli = ((numerator * 1000u) + (1u << (s - 1u))) >> s;
        }
    }

    uart_putc(sign ? '-' : '+');
    uart_dec32(milli / 1000u);
    uart_putc('.');
    {
        uint32_t frac = milli % 1000u;
        uart_putc((char)('0' + (frac / 100u)));
        uart_putc((char)('0' + ((frac / 10u) % 10u)));
        uart_putc((char)('0' + (frac % 10u)));
    }
}

/* Print a signed integer. */
static void uart_dec32s(int32_t value)
{
    if (value < 0) {
        uart_putc('-');
        uart_dec32((uint32_t)(-value));
    } else {
        uart_dec32((uint32_t)value);
    }
}

/* Print a signed value expressed in thousandths. */
static void uart_milli(int32_t milli)
{
    uint32_t m = (milli < 0) ? (uint32_t)(-milli) : (uint32_t)milli;
    uart_putc(milli < 0 ? '-' : '+');
    uart_dec32(m / 1000u);
    uart_putc('.');
    uart_putc((char)('0' + ((m / 100u) % 10u)));
    uart_putc((char)('0' + ((m / 10u) % 10u)));
    uart_putc((char)('0' + (m % 10u)));
}


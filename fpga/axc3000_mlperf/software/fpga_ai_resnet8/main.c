/* Bounded throughput sweep for the latency / fps figure. */
static void throughput_sweep(void)
{
    uint16_t raw[OUTPUT_WORDS_MAX];
    uint32_t dla_cycles = 0u;
    uint32_t frame_cycles = 0u;
    uint32_t frame;
    uint32_t completed = 0u;
    uint32_t dla_total = 0u;
    uint32_t frame_total = 0u;
    uint32_t tail_total = 0u;
    uint32_t class_histogram[OUTPUT_CLASSES];
    static uint8_t level[FC_TAIL_CHANNELS];  /* sized for the unused FC tail */
    int32_t score[OUTPUT_CLASSES];
    uint32_t negatives;
    uint32_t sweep_core_before = ai_read(AI_CSR_CORE_CLOCKS_ACTIVE_LO);
    uint32_t sweep_core_clocks;
    uint32_t sweep_begin = clock_ticks32();
    uint32_t sweep_cycles;
    uint32_t sweep_hash_even = 2166136261u;  /* INPUT_ZERO frames           */
    uint32_t sweep_hash_odd  = 2166136261u;  /* INPUT_SYNTHETIC_NHWC frames */

    for (frame = 0; frame < OUTPUT_CLASSES; ++frame)
        class_histogram[frame] = 0u;

    uart_puts("sweep start frames=");
    uart_dec32(SWEEP_FRAMES);
    uart_putc('\n');

    for (frame = 0; frame < SWEEP_FRAMES; ++frame) {
        uint32_t kind = (frame & 1u) ? INPUT_SYNTHETIC_NHWC : INPUT_ZERO;
        uint32_t tail_begin;
        if (run_inference(kind, raw, &dla_cycles, &frame_cycles) != 0) {
            uart_puts("sweep abort frame=");
            uart_dec32(frame);
            uart_putc('\n');
            break;
        }
        /* The classifier tail is part of the end-to-end frame, so time it. */
        tail_begin = clock_ticks32();
#if USE_FC_TAIL
        class_histogram[classify_features(raw, level, score, &negatives)] += 1u;
#else
        class_histogram[argmax_logits(raw)] += 1u;
        (void)level; (void)score; (void)negatives;
#endif
        tail_total += (uint32_t)(clock_ticks32() - tail_begin);
        /* Per-parity output hashes: the sweep alternates two different images,
         * so these two must differ if the egress tracks the input. */
        if (kind == INPUT_ZERO)
            sweep_hash_even = (sweep_hash_even ^ feature_hash(raw)) * 16777619u;
        else
            sweep_hash_odd = (sweep_hash_odd ^ feature_hash(raw)) * 16777619u;
        ai_write(AI_CSR_INTERRUPT_CONTROL, AI_IRQ_ALL);
        dla_total += dla_cycles;
        frame_total += frame_cycles;
        ++completed;
    }
    sweep_cycles = (uint32_t)(clock_ticks32() - sweep_begin);
    sweep_core_clocks =
        (uint32_t)(ai_read(AI_CSR_CORE_CLOCKS_ACTIVE_LO) - sweep_core_before);

    uart_puts("sweep hash_zero=0x");
    uart_hex32(sweep_hash_even);
    uart_puts(" hash_nhwc=0x");
    uart_hex32(sweep_hash_odd);
    uart_puts(sweep_hash_even == sweep_hash_odd
                  ? " VERDICT=frozen_egress\n"
                  : " VERDICT=input_varying\n");

    uart_puts("sweep end completed=");
    uart_dec32(completed);
    if (completed != 0u) {
        uint32_t mean_dla = dla_total / completed;
        uint32_t mean_tail = tail_total / completed;
        uint32_t mean_total = (dla_total + tail_total) / completed;
        uart_puts(" mean_dla_cycles=");
        uart_dec32(mean_dla);
        uart_puts(" mean_tail_cycles=");
        uart_dec32(mean_tail);
        uart_puts(" mean_dla_plus_tail_cycles=");
        uart_dec32(mean_total);
        uart_puts(" mean_frame_cycles=");
        uart_dec32(frame_total / completed);
        /* mtime ticks are 10 ns because mtime stays in the 100 MHz outclk0
         * domain.  This conversion is deliberately NOT scaled by
         * DLA_CLOCK_HZ -- doing so would double-count the clock split. */
        uart_puts(" mean_dla_ns_from_mtime=");
        uart_dec32(mean_dla * (1000u / (CPU_CLOCK_HZ / 1000000u)));
        uart_puts(" mean_core_clocks_per_frame=");
        uart_dec32(sweep_core_clocks / completed);
        uart_puts(" sweep_core_per_mtime_x1000=");
        uart_dec32(sweep_cycles
                       ? (sweep_core_clocks
                          / (sweep_cycles / 1000u ? sweep_cycles / 1000u : 1u))
                       : 0u);
        uart_puts(" fps_dla_only=");
        uart_dec32(CPU_CLOCK_HZ / (mean_dla ? mean_dla : 1u));
        uart_puts(" fps_dla_plus_tail=");
        uart_dec32(CPU_CLOCK_HZ / (mean_total ? mean_total : 1u));
        uart_puts(" fps_end_to_end=");
        uart_dec32(CPU_CLOCK_HZ / (frame_total / completed ? frame_total / completed : 1u));
        uart_puts(" class_histogram:");
        for (frame = 0; frame < OUTPUT_CLASSES; ++frame) {
            uart_putc(' ');
            uart_dec32(class_histogram[frame]);
        }
    }
    uart_puts(" sweep_cycles=");
    uart_dec32(sweep_cycles);
    uart_puts(" diagnostics=0x");
    uart_hex32(ai_read(AI_CSR_DESCRIPTOR_DIAGNOSTICS));
    uart_puts(" completion_count=");
    uart_dec32(ai_read(AI_CSR_COMPLETION_COUNT));
    uart_putc('\n');
}

/* --------------------------------------------------------------------------
 * Address-mapping / input-dependence discriminator
 *
 * The first board run showed the feature writer emitting a fixed 24-byte
 * payload at io_base+8192 regardless of the input tensor.  Two explanations
 * survive that observation:
 *   (H1) the DLA genuinely ignores the input data (defect), or
 *   (H2) the feature reader is fetching from somewhere other than the region
 *        the firmware writes, so it always sees the same constant bytes.
 *
 * These probes separate them without another Quartus compile:
 *   probe_fill()     fills the ENTIRE 16 KiB pseudo-DDR with one FP16 value,
 *                    so no matter where in the RAM the reader looks it sees
 *                    different data between two runs.  If the output still
 *                    does not move, H2 is dead.
 *   probe_relocate() moves the whole io buffer to a non-zero base and programs
 *                    CSR 536 with that base.  If the writer's 24 bytes appear
 *                    at newbase+8192 then the base register is honoured by the
 *                    DMA, which means the reader is reading newbase+0 too.
 * ------------------------------------------------------------------------ */

static void ddr_fill_half(uint16_t half)
{
    uint32_t i;
    uint32_t pattern = ((uint32_t)half << 16) | (uint32_t)half;
    for (i = 0; i < DLA_DDR_BYTES; i += 4u)
        dla_ddr32[i >> 2] = pattern;
}

static void probe_report(const char *tag, uint32_t out_off)
{
    uint32_t i;
    uart_puts("probe tag=");
    uart_puts(tag);
    uart_puts(" out_off=");
    uart_dec32(out_off);
    uart_puts(" bytes:");
    for (i = 0; i < 24u; ++i) {
        if ((i & 7u) == 0u)
            uart_putc(' ');
        uart_hex8(dla_ddr8[out_off + i]);
    }
    uart_puts(" irq=0x");
    uart_hex32(ai_read(AI_CSR_INTERRUPT_CONTROL));
    uart_puts(" completion_count=");
    uart_dec32(ai_read(AI_CSR_COMPLETION_COUNT));
    uart_putc('\n');
    ai_write(AI_CSR_INTERRUPT_CONTROL, AI_IRQ_ALL);
}

static int probe_run(uint32_t io_base)
{
    uint32_t before = ai_read(AI_CSR_COMPLETION_COUNT);
    uint32_t start;
    ai_write(AI_CSR_INPUT_OUTPUT_BASE_ADDR, io_base);
    start = clock_ticks32();
    while (ai_read(AI_CSR_COMPLETION_COUNT) == before) {
        if ((uint32_t)(clock_ticks32() - start) > TIMEOUT_CYCLES) {
            uart_puts("probe timeout io_base=");
            uart_dec32(io_base);
            uart_putc('\n');
            return -1;
        }
    }
    return 0;
}

/* Fill the whole RAM with `half`, then run one inference at io_base 0. */
static void probe_fill(const char *tag, uint16_t half)
{
    ddr_fill_half(half);
    /* Re-poison only the 24 bytes the writer touches so the readback below is
     * unambiguous even if the fill value coincides with a logit encoding. */
    dla_ddr32[(OUTPUT_OFFSET +  0u) >> 2] = OUTPUT_SENTINEL;
    dla_ddr32[(OUTPUT_OFFSET +  4u) >> 2] = OUTPUT_SENTINEL;
    dla_ddr32[(OUTPUT_OFFSET +  8u) >> 2] = OUTPUT_SENTINEL;
    dla_ddr32[(OUTPUT_OFFSET + 12u) >> 2] = OUTPUT_SENTINEL;
    dla_ddr32[(OUTPUT_OFFSET + 16u) >> 2] = OUTPUT_SENTINEL;
    dla_ddr32[(OUTPUT_OFFSET + 20u) >> 2] = OUTPUT_SENTINEL;
    if (probe_run(IO_BASE_ADDR) == 0)
        probe_report(tag, OUTPUT_OFFSET);
}

/* Move the io buffer to `base` and run one inference there.  4096 + 8704 =
 * 12800, comfortably inside the 16384-byte RAM. */
static void probe_relocate(const char *tag, uint32_t base, uint32_t input_kind)
{
    uint32_t h;
    uint32_t w;
    uint32_t c;
    uint32_t i;

    for (i = 0; i < DLA_DDR_BYTES; i += 4u)
        dla_ddr32[i >> 2] = OUTPUT_SENTINEL;

    for (h = 0; h < IMAGE_HEIGHT; ++h) {
        for (w = 0; w < IMAGE_WIDTH; ++w) {
            uint32_t pixel = h * IMAGE_WIDTH + w;
            for (c = 0; c < INPUT_CVEC; ++c) {
                uint16_t half = (c < IMAGE_CHANNELS)
                    ? uint8_to_half(input_value(input_kind,
                                                pixel * IMAGE_CHANNELS + c))
                    : 0u;
                uint32_t byte_offset = base + ((pixel * INPUT_CVEC + c) << 1);
                dla_ddr8[byte_offset]      = (uint8_t)half;
                dla_ddr8[byte_offset + 1u] = (uint8_t)(half >> 8);
            }
        }
    }

    if (probe_run(base) == 0) {
        probe_report(tag, base + OUTPUT_OFFSET);
        /* Show that nothing landed at the OLD location. */
        uart_puts("probe tag=");
        uart_puts(tag);
        uart_puts(" old_location_off=");
        uart_dec32(OUTPUT_OFFSET);
        uart_puts(" bytes:");
        for (i = 0; i < 8u; ++i)
            uart_hex8(dla_ddr8[OUTPUT_OFFSET + i]);
        uart_putc('\n');
    }
}

static void diag_writer(void)
{
    uart_puts("diag_writer start\n");

    /* H2 test: whole-RAM fills.  Any reader address whatsoever sees a
     * different tensor between these three runs. */
    probe_fill("fill_0.0",   0x0000u); /* FP16 0.0   */
    probe_fill("fill_1.0",   0x3c00u); /* FP16 1.0   */
    probe_fill("fill_255.0", 0x5bf8u); /* FP16 255.0 */
    probe_fill("fill_0.0_again", 0x0000u);

    /* Base-register test: same tensor, different io base. */
    probe_relocate("reloc0_nhwc",    IO_BASE_ADDR, INPUT_SYNTHETIC_NHWC);
    probe_relocate("reloc4096_nhwc", 4096u,        INPUT_SYNTHETIC_NHWC);
    probe_relocate("reloc4096_zero", 4096u,        INPUT_ZERO);

    uart_puts("diag_writer end completion_count=");
    uart_dec32(ai_read(AI_CSR_COMPLETION_COUNT));
    uart_putc('\n');
}

int main(void)
{
    uint16_t raw[OUTPUT_WORDS_MAX];
    uint32_t dla_cycles = 0u;
    uint32_t frame_cycles = 0u;
    static uint32_t snap_pre[PROFILE_POINTS];
    static uint32_t blk_pre[PROFILE_POINTS * PROFILE_FIELDS];
    static uint32_t blk_inf1[PROFILE_POINTS * PROFILE_FIELDS];
    uint32_t completion_before;
    uint32_t core_clocks_before;
    uint32_t active_clocks_before;

    uart_puts("fpga_ai_resnet8 build=phase11-300mhz arch=V1_8x8_AGX3"
              " ocp=0 params=ddr graph=resnet8_fpga_logits tail=fpga csr=0x");
    uart_hex32(FPGA_AI_CSR_BASE);
    uart_puts(" pseudo_ddr_io=0x");
    uart_hex32(DLA_DDR_BASE);
    uart_puts(" io_base=0x");
    uart_hex32(IO_BASE_ADDR);
    uart_puts(" input_bytes=");
    uart_dec32(INPUT_BYTES);
    uart_puts(" output_offset=");
    uart_dec32(OUTPUT_OFFSET);
    uart_puts(" cpu_mtime_clock=");
    uart_dec32(CPU_CLOCK_HZ);
    uart_puts(" dla_core_clock=");
    uart_dec32(DLA_CLOCK_HZ);
    uart_putc('\n');

    initialize_synthetic_image();

    if (ddr_selftest() != 0)
        uart_puts("FATAL pseudo-DDR self-test failed: Nios V cannot access dla_io\n");

    /* Must follow ddr_selftest(), which scribbles patterns across dla_io.
     * Lays down the Cvec padding channels once so ddr_write_input() never has
     * to touch them again. */
    ddr_zero_input();

    /* Must precede start_writer(): the DLA fetches the config stream from
     * dla_par0 as soon as the first descriptor is queued. */
    if (param_verify() != 0)
        uart_puts("FATAL continuing anyway so the failure mode is recorded\n");

    start_writer();
    discovery_dump();

    /* Measure the clock split before any inference runs, so the ratio is not
     * confounded by job activity. */
    measure_dla_clock("idle");

    completion_before = ai_read(AI_CSR_COMPLETION_COUNT);
    core_clocks_before = ai_read(AI_CSR_CORE_CLOCKS_ACTIVE_LO);
    active_clocks_before = ai_read(AI_CSR_CLOCKS_ACTIVE_LO);

    profile_snapshot(snap_pre);
    profile_print_absolute("post_reset", snap_pre);
    profile_block_snapshot(blk_pre);

#if DIAG_WRITER
    diag_writer();
#endif

    /* Instrumented inference 1: the first frame after IP reset. */
    if (run_inference(INPUT_ZERO, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("zero_inf1", raw, dla_cycles, frame_cycles);
    ddr_dump_output(128u);
    report_and_clear_status("zero_inf1");
    profile_block_snapshot(blk_inf1);
    profile_block_print_deltas("inf1", blk_pre, blk_inf1);
    uart_puts("progress tag=inf1 completions_delta=");
    uart_dec32(ai_read(AI_CSR_COMPLETION_COUNT) - completion_before);
    uart_puts(" active_clocks_delta=");
    uart_dec32(ai_read(AI_CSR_CLOCKS_ACTIVE_LO) - active_clocks_before);
    uart_puts(" core_clocks_delta=");
    uart_dec32(ai_read(AI_CSR_CORE_CLOCKS_ACTIVE_LO) - core_clocks_before);
    uart_putc('\n');

    /* Input-dependence check: four distinct patterns.  The correctness gate is
     * synthetic_nhwc -> class 6 with the oracle logits. */
    if (run_inference(INPUT_ZERO, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("zero", raw, dla_cycles, frame_cycles);
    report_and_clear_status("zero");

    if (run_inference(INPUT_ALL_255, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("all255", raw, dla_cycles, frame_cycles);
    report_and_clear_status("all255");

    if (run_inference(INPUT_SYNTHETIC_NHWC, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("synthetic_nhwc", raw, dla_cycles, frame_cycles);
    ddr_dump_output(128u);
    report_and_clear_status("synthetic_nhwc");

    if (run_inference(INPUT_SYNTHETIC_NCHW, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("synthetic_nchw", raw, dla_cycles, frame_cycles);
    report_and_clear_status("synthetic_nchw");

    /* Repeat the gate input once more to show run-to-run stability. */
    if (run_inference(INPUT_SYNTHETIC_NHWC, raw, &dla_cycles, &frame_cycles) != 0)
        return 1;
    print_output("synthetic_nhwc_repeat", raw, dla_cycles, frame_cycles);
    report_and_clear_status("synthetic_nhwc_repeat");

    uart_puts("final license=0x");
    uart_hex32(ai_read(AI_CSR_LICENSE));
    uart_puts(" irq=0x");
    uart_hex32(ai_read(AI_CSR_INTERRUPT_CONTROL));
    uart_puts(" diagnostics=0x");
    uart_hex32(ai_read(AI_CSR_DESCRIPTOR_DIAGNOSTICS));
    uart_puts(" completion_count=");
    uart_dec32(ai_read(AI_CSR_COMPLETION_COUNT));
    uart_puts(" uart_dropped=");
    uart_dec32(uart_dropped_chars);
    uart_putc('\n');
    uart_puts("inferences_this_run=6\n");
    uart_puts("bringup done\n");

#if !DIAG_WRITER
    throughput_sweep();
#else
    (void)throughput_sweep;
#endif

    uart_puts_nb("done total_inferences=");
    uart_dec32_nb(ai_read(AI_CSR_COMPLETION_COUNT));
    uart_puts_nb("\n");
    return 0;
}

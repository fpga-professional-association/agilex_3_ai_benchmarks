/* --------------------------------------------------------------------------
 * Parameter image (config + filters) verification
 *
 * dla_par0/dla_par1 are initialised from .mif at device programming time.  The
 * MIF is written little-endian: word N holds the 64 bits the AXI slave returns
 * for byte address 8N, so byte 8N+0 is bits [7:0].  If that convention were
 * wrong the DLA would fetch a byte-reversed config stream and misbehave in a
 * way that looks exactly like the defect under investigation, so the image is
 * checked here before the first inference -- and repaired in place if the
 * check fails on the byte-swapped interpretation, which removes any dependence
 * on getting the MIF endianness right at synthesis time.
 * ------------------------------------------------------------------------ */

#define PARAM_FNV1A   0xe0a8c009u  /* scripts/make_dla_param_mif.py output */
#define PARAM_WORD0_LO 0x00000000u /* image bytes 0..3   */
#define PARAM_WORD0_HI 0x02000008u /* image bytes 4..7   */

static volatile uint32_t *const dla_par32 = (volatile uint32_t *)DLA_PAR_BASE;
static volatile uint8_t  *const dla_par8  = (volatile uint8_t *)DLA_PAR_BASE;

static uint32_t param_fnv1a(void)
{
    uint32_t i;
    uint32_t h = 0x811c9dc5u;
    for (i = 0; i < DLA_PAR_BYTES; ++i) {
        h ^= (uint32_t)dla_par8[i];
        h *= 0x01000193u;
    }
    return h;
}

/* Swap the two 32-bit halves of every 64-bit word and reverse the bytes in
 * each half, i.e. undo a big-endian MIF interpretation. */
static void param_byteswap64(void)
{
    uint32_t w;
    for (w = 0; w < DLA_PAR_CAPACITY / 8u; ++w) {
        uint32_t lo = dla_par32[w * 2u];
        uint32_t hi = dla_par32[w * 2u + 1u];
        uint32_t nlo = ((hi >> 24) & 0xffu) | ((hi >> 8) & 0xff00u) |
                       ((hi << 8) & 0xff0000u) | ((hi << 24) & 0xff000000u);
        uint32_t nhi = ((lo >> 24) & 0xffu) | ((lo >> 8) & 0xff00u) |
                       ((lo << 8) & 0xff0000u) | ((lo << 24) & 0xff000000u);
        dla_par32[w * 2u]      = nlo;
        dla_par32[w * 2u + 1u] = nhi;
    }
}

static int param_verify(void)
{
    uint32_t hash;

    uart_puts("param base=0x");
    uart_hex32(DLA_PAR_BASE);
    uart_puts(" bytes=");
    uart_dec32(DLA_PAR_BYTES);
    uart_puts(" word0=0x");
    uart_hex32(dla_par32[1]);
    uart_hex32(dla_par32[0]);
    uart_puts(" word1=0x");
    uart_hex32(dla_par32[3]);
    uart_hex32(dla_par32[2]);
    uart_putc('\n');

    hash = param_fnv1a();
    uart_puts("param fnv1a=0x");
    uart_hex32(hash);
    uart_puts(" expected=0x");
    uart_hex32(PARAM_FNV1A);
    uart_putc('\n');

    if (hash == PARAM_FNV1A) {
        uart_puts("param OK mif initialisation reached silicon intact\n");
        return 0;
    }

    uart_puts("param MISMATCH trying byte-swapped interpretation\n");
    param_byteswap64();
    hash = param_fnv1a();
    uart_puts("param after_swap fnv1a=0x");
    uart_hex32(hash);
    uart_putc('\n');
    if (hash == PARAM_FNV1A) {
        uart_puts("param REPAIRED mif word endianness was reversed\n");
        return 0;
    }

    /* Undo the swap so the reported state is the as-programmed one. */
    param_byteswap64();
    uart_puts("FATAL param image in dla_par0/dla_par1 is not the compiled "
              "config+filter blob\n");
    return -1;
}

/* Prove the Nios V side of the pseudo-DDR is wired and coherent before any
 * inference is attempted.  A failure here means the qsys address map, not the
 * DLA, is at fault. */
static int ddr_selftest(void)
{
    uint32_t i;
    uint32_t errors = 0u;
    for (i = 0; i < DLA_DDR_BYTES; i += 4u)
        dla_ddr32[i >> 2] = i * 2654435761u;
    for (i = 0; i < DLA_DDR_BYTES; i += 4u) {
        if (dla_ddr32[i >> 2] != i * 2654435761u)
            ++errors;
    }
    uart_puts("ddr_selftest base=0x");
    uart_hex32(DLA_DDR_BASE);
    uart_puts(" bytes=");
    uart_dec32(DLA_DDR_BYTES);
    uart_puts(" errors=");
    uart_dec32(errors);
    uart_putc('\n');
    for (i = 0; i < DLA_DDR_BYTES; i += 4u)
        dla_ddr32[i >> 2] = 0u;
    return errors == 0u ? 0 : -1;
}


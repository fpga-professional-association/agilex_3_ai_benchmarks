    uart_dec32(tail_cycles);
    uart_puts(" changed_words=");
    uart_dec32(ddr_output_changed_words());
    uart_puts(" feat_hash=0x");
    uart_hex32(feature_hash(raw));
    uart_puts(" feat_sum=");
    uart_dec32(level_sum);
    uart_puts(" feat_neg=");

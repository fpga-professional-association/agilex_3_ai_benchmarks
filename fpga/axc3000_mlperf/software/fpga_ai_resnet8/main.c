static uint16_t uint8_to_half(uint32_t value)
{
    /* All values are integers in [0,255], so conversion to binary16 is exact. */
    uint32_t exponent = 0u;
    uint32_t mantissa;
    if (value == 0u)
        return 0u;
    while ((1u << (exponent + 1u)) <= value)
        ++exponent;
    mantissa = value - (1u << exponent);
    return (uint16_t)(((exponent + 15u) << 10) | (mantissa << (10u - exponent)));
}

static void initialize_synthetic_image(void)
{
    uint32_t state = 0x13579bdfu;
    uint32_t i;
    for (i = 0; i < IMAGE_VALUES; ++i) {
        state = state * 1664525u + 1013904223u;
        synthetic_image[i] = (uint8_t)((((state >> 24) ^ (i * 29u)) & 0xffu) ^ 0x80u);
    }
}

/* Offset is an index into the NHWC image (pixel-major, then channel). */
static uint32_t input_value(uint32_t input_kind, uint32_t offset)
{
    if (input_kind == INPUT_ZERO)
        return 0u;
    if (input_kind == INPUT_ALL_255)
        return 255u;
    if (input_kind == INPUT_SYNTHETIC_NCHW) {
        uint32_t channel = offset / (IMAGE_WIDTH * IMAGE_HEIGHT);
        uint32_t pixel = offset % (IMAGE_WIDTH * IMAGE_HEIGHT);
        return synthetic_image[pixel * IMAGE_CHANNELS + channel];
    }
    return synthetic_image[offset];
}

/* --------------------------------------------------------------------------
 * Pseudo-DDR access
 * ------------------------------------------------------------------------ */

/* Writing the 16 KiB input tensor is the end-to-end bottleneck: the Nios V is
 * the only initiator on this path, so the frame rate is set by what the copy
 * costs, not by the DLA.  Phase 9 issued two 8-bit stores per FP16 element --
 * 16384 single-byte transactions per frame -- and walked all INPUT_CVEC (8)
 * channels of every pixel even though only IMAGE_CHANNELS (3) carry data.
 *
 * Measured on hardware, simply pairing the byte stores into 32-bit stores was
 * NOT a win: it cut transactions 4x but cost 13% more time, because this loop
 * is dominated by the per-element uint8_to_half()/input_value() work and the
 * extra per-element branch outweighed the saved stores.  The real win is to
 * stop touching the padding channels at all: 8192 loop iterations per frame
 * become 1024*2 = 2048, and 16384 byte stores become 2048 word stores.
 *
 * Each pixel occupies INPUT_CVEC contiguous halves, so pixel * INPUT_CVEC is
 * even and every channel pair starts on a 4-byte boundary.  INPUT_CVEC must
 * stay even for that to hold. */
#if (INPUT_CVEC & 1u) != 0u
#error "ddr_write_input packs channel pairs into 32-bit words; INPUT_CVEC must be even"
#endif

/* Channels IMAGE_CHANNELS..INPUT_CVEC-1 are Cvec padding: they are zero for
 * every frame, forever.  ddr_zero_input() lays them down once and nothing else
 * ever writes the input region, so the per-frame copy can skip them entirely
 * instead of re-writing zeros 5120 times a frame. */
static void ddr_zero_input(void)
{
    uint32_t i;
    for (i = 0; i < INPUT_BYTES; i += 4u)
        dla_ddr32[(INPUT_OFFSET + i) >> 2] = 0u;
}

static void ddr_write_input(uint32_t input_kind)
{
    uint32_t pixel;
    const uint32_t pixels = IMAGE_WIDTH * IMAGE_HEIGHT;

    for (pixel = 0; pixel < pixels; ++pixel) {
        /* NHWC source base and the first of this pixel's INPUT_CVEC/2 words. */
        uint32_t src  = pixel * IMAGE_CHANNELS;
        uint32_t word = (INPUT_OFFSET >> 2) + pixel * (INPUT_CVEC / 2u);
        uint32_t c;

        for (c = 0; c < IMAGE_CHANNELS; c += 2u) {
            uint32_t lo = uint8_to_half(input_value(input_kind, src + c));
            uint32_t hi = (c + 1u < IMAGE_CHANNELS)
                              ? uint8_to_half(input_value(input_kind,
                                                          src + c + 1u))
                              : 0u;  /* odd channel count: pad the high half */
            dla_ddr32[word + (c >> 1)] = lo | (hi << 16);
        }
    }
}

static void ddr_poison_output(void)
{
    uint32_t i;
    for (i = 0; i < OUTPUT_BYTES; i += 4u)
        dla_ddr32[(OUTPUT_OFFSET + i) >> 2] = OUTPUT_SENTINEL;
}

static void ddr_read_output(uint16_t *raw)
{
    uint32_t c;
    for (c = 0; c < FEATURE_CHANNELS; ++c) {
        uint32_t byte_offset = OUTPUT_OFFSET + (c << 1);
        raw[c] = (uint16_t)((uint32_t)dla_ddr8[byte_offset] |
                            ((uint32_t)dla_ddr8[byte_offset + 1u] << 8));
    }
}


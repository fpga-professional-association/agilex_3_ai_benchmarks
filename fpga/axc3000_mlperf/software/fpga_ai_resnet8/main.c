static const int32_t fc_bias[OUTPUT_CLASSES] = {
    -23, -40, 5, 18, 12, -34, 44, -28, -2, 46,
};

/* IEEE binary16 -> unsigned Q16.16.  Exact for every encoding the truncated
 * tensor can hold ([0, 32.402634] snapped to a 256-level grid).
 *   E != 0 : value = (1024 + M) * 2^(E - 25)  ->  Q16.16 = (1024+M) << (E-9)
 *   E == 0 : value = M * 2^-24                ->  Q16.16 = M >> 8
 * The tensor is post-ReLU, so a negative encoding is a defect indicator; it is
 * clamped to zero and counted by the caller. */
static uint32_t half_to_q16_16(uint16_t h)
{
    uint32_t exponent = (uint32_t)((h >> 10) & 0x1fu);
    uint32_t mantissa = (uint32_t)(h & 0x3ffu);
    uint32_t numerator;
    int32_t shift;

    if ((h & 0x8000u) != 0u)
        return 0u;                     /* negative: clamped by the ReLU model */
    if (exponent == 0x1fu)
        return FEATURE_Q16_CEILING;    /* inf / nan */
    if (exponent == 0u)
        return mantissa >> 8;          /* subnormal, < 6e-5 */

    numerator = 1024u + mantissa;
    shift = (int32_t)exponent - 9;
    if (shift >= 0) {
        if (shift > 21)
            return FEATURE_Q16_CEILING;
        return numerator << (uint32_t)shift;
    }
    {
        uint32_t s = (uint32_t)(-shift);
        if (s >= 32u)
            return 0u;
        return (numerator + (1u << (s - 1u))) >> s;
    }
}

/* Recover the TFLite integer activation level u = xq + 128 in [0,255].
 * u = round(value / step) computed as (q16 * 2^16/step) >> 32 with the
 * multiply split at bit 12 so both partial products stay under 2^32:
 *   q16 <= 0x210000 -> qh <= 528  -> qh*515751 <= 2.73e8
 *   ql  <  4096                   -> ql*515751 <= 2.11e9                    */
static uint32_t feature_level(uint16_t h)
{
    uint32_t q16 = half_to_q16_16(h);
    uint32_t qh;
    uint32_t ql;
    uint32_t level;

    if (q16 > FEATURE_Q16_CEILING)
        q16 = FEATURE_Q16_CEILING;
    qh = q16 >> 12;
    ql = q16 & 0xfffu;
    level = ((qh * FEATURE_INV_STEP_Q16) +
             ((ql * FEATURE_INV_STEP_Q16) >> 12) + (1u << 19)) >> 20;
    return level > 255u ? 255u : level;
}

/* round(acc * M) with M = 0.0225920333, split at bit 10:
 *   |acc| <= 255*127*64 + 46 = 2072686 -> ah <= 2024 -> ah*1516126 <= 3.07e9
 *   al < 1024 -> al*1516126 <= 1.56e9, shifted down by 10 -> <= 1.52e6
 * Worst-case sum 3.07e9 + 1.52e6 + 32768 stays below 2^32.  Verified against
 * exact double arithmetic over the whole acc range: max deviation 1 LSB, and
 * over the realistic |acc| <= 20000 range it deviates on 0.006% of values. */
static int32_t fc_requantize(int32_t acc)
{
    uint32_t magnitude = (acc < 0) ? (uint32_t)(-acc) : (uint32_t)acc;
    uint32_t ah = magnitude >> 10;
    uint32_t al = magnitude & 0x3ffu;
    uint32_t total_q16 = (ah * FC_M_Q26) + ((al * FC_M_Q26) >> 10);
    int32_t scaled = (int32_t)((total_q16 + 32768u) >> 16);
    return (acc < 0) ? -scaled : scaled;
}

static int32_t clamp_int8(int32_t value)
{
    if (value < -128) return -128;
    if (value > 127) return 127;
    return value;
}

/* Full tail: 64 FP16 reads, 640 MACs, 10 requantizations, argmax.
 * score[j] is the output-FakeQuantize integer relative to the zero point, i.e.
 * exactly the reference INT8 score minus 24; logit = score * output_scale. */
static uint32_t classify_features(const uint16_t *raw, uint8_t *level,
                                  int32_t *score, uint32_t *negatives)
{
    uint32_t c;
    uint32_t j;
    uint32_t best = 0u;

    *negatives = 0u;
    for (c = 0; c < FC_TAIL_CHANNELS; ++c) {
        if ((raw[c] & 0x8000u) != 0u && (raw[c] & 0x7fffu) != 0u)
            ++(*negatives);
        level[c] = (uint8_t)feature_level(raw[c]);
    }

    for (j = 0; j < OUTPUT_CLASSES; ++j) {
        int32_t acc = fc_bias[j];
        for (c = 0; c < FC_TAIL_CHANNELS; ++c)
            acc += (int32_t)level[c] * (int32_t)fc_weight[j][c];
        score[j] = fc_requantize(acc);
    }

    for (j = 1; j < OUTPUT_CLASSES; ++j) {
        if (score[j] > score[best])
            best = j;
    }
    return best;
}

static int ai_debug_read(uint32_t address, uint32_t *value)
{
    uint32_t start = clock_ticks32();
    ai_write(AI_CSR_DEBUG_NETWORK_ADDR, address);
    while (ai_read(AI_CSR_DEBUG_NETWORK_VALID) == 0u) {
        if ((uint32_t)(clock_ticks32() - start) > TIMEOUT_CYCLES)
            return -1;
    }
    *value = ai_read(AI_CSR_DEBUG_NETWORK_DATA);
    return 0;
}

/* The freeze/unfreeze commands are issued through the same address register
 * as a read.  Any returned data is meaningless and is discarded. */
static void ai_debug_command(uint32_t address)
{
    uint32_t scratch;
    (void)ai_debug_read(address, &scratch);
    delay_ticks(256u);
}


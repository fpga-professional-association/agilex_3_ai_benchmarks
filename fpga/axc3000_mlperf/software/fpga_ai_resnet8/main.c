/* Phase 9 firmware: CoreDLA on the VENDOR reference architecture with
 * DDR-resident parameters.
 *
 * The architecture V1_8x8_AGX3 is the vendor example architecture
 * AGX3_Small_NoSoftmax.arch with only two forced deviations
 * (pe_array.enable_scale and activation.enable_round_clamp, which the compiler
 * refuses to compile a FakeQuantize graph without) and k_vector/c_vector
 * reduced 16 -> 8 to fit Agilex 3.  Decisively, it has NO on-chip parameters:
 * the config stream and the filters now live in "DDR" and are fetched by the
 * DMA config reader and filter reader.  enable_on_chip_parameters was present
 * in every architecture that produced a frozen output, and is the option this
 * build exists to exonerate or convict.
 *
 * The pseudo-DDR is three on-chip RAM blocks (intel_onchip_memory rounds its
 * address width up to a power of two, so one 200 KiB RAM would cost a full
 * 256 KiB of M20K):
 *
 *   DLA ddr_axi     Nios V data master   instance   size    contents
 *   0x00000         0x00100000           dla_par0   128 KiB config+filter[0..131071]
 *   0x20000         0x00120000           dla_par1    64 KiB config+filter[131072..186879]
 *   0x30000         0x00130000           dla_io      32 KiB input at +0, output at +16384
 *
 * dla_par0/dla_par1 are initialised at device programming time from
 * fpga/axc3000_mlperf/mem/dla_par{0,1}.mif, generated by
 * scripts/make_dla_param_mif.py from the compiler's own
 * compiled_result_t::config_filter_bias_scale_array.  Both halves are
 * 4 KiB-aligned, so no AXI burst can straddle the slave boundary.
 *
 * The CSR sequence below follows, register for register, the
 * !ENABLE_ON_CHIP_PARAMETERS else-branch of
 *   C:\altera_pro\2026.1.1\fpga_ai_suite\dla\example_ip_cores\altera_ai_ip\
 *     sim\sequential_tb\AGX3_Small_NoSoftmax_AGX3\
 *     tb_csr_driver_AGX3_Small_NoSoftmax_AGX3.sv
 * namely lines 201-202 (IP_RESET), 210-211 (INTERRUPT_MASK), 232-233
 * (INTERMEDIATE_BASE_ADDR), 239-247 (CONFIG_BASE_ADDR and
 * CONFIG_RANGE_MINUS_TWO -- now WRITTEN, this is the branch we are finally in),
 * 259-271 (INPUT_OUTPUT_BASE_ADDR once per inference - each write enqueues one
 * descriptor), and 288-301 for the completion/interrupt readback and W1C clear.
 *
 * CONFIG_RANGE_MINUS_TWO is tb_top:605, num_config_words =
 * config_bytes / CONFIG_READER_DATA_BYTES, minus two.  For this build
 * 19456 / 8 - 2 = 2430.  (Note the compiled result's own num_config_words
 * field counts 32-bit words, 4864; the CSR wants 64-bit config-reader words.)
 *
 * The buffer layout is the compiler's, from
 *   build/fpga_ai/compile_vendor_8x8/TensorFlow_Lite_Frontend_IR/
 *     ddr_buffer_info_TensorFlow_Lite_Frontend_IR_0.txt
 *   inputOutputBuffer size: 16896
 *     Inputs:  image_u8_nchw: offset 0, size: 16384
 *     Output:  offset 16384, size: 512
 *   configFilterBuffer size: 186880
 *     Config: offset 0, size: 19456
 *     Filter: offset 19456, size: 167424
 *   interBuffer size: 0           (stream buffer absorbs all intermediates)
 * which matches tb_top_AGX3_Small_NoSoftmax_AGX3.sv:577 ("filter data must
 * come immediately after config data") and :582 ("output data must come
 * immediately after input data").
 */


#!/usr/bin/env python3
"""Turn the DLA config+filter DDR image into Quartus .mif files for the two
on-chip parameter RAMs of the AXC3000 pseudo-DDR.

The image itself is extracted from a `dla_compiler --foutput-format
dla_compiled_result` blob: it is the single element of
`compiled_result_t::config_filter_bias_scale_array`
(config at offset 0, filters immediately after -- the DLA derives the filter
address from the config stream, there is no separate filter base CSR).

MIF word N carries the 64 bits that the AXI slave returns for byte address
8*N, little-endian: byte 8*N+0 is bits [7:0], so the hex digits run from the
highest-addressed byte down to the lowest.

Usage:
  make_dla_param_mif.py <compiled_result.bin> <total_bytes> <outdir> [layout]

`layout` is an optional comma-separated list of `name:bytes` RAM instances, in
DLA address order; it defaults to the Phase 9-11 two-block pseudo-DDR.  Phase 12
(k16c8, 205,056-byte image) uses
`dla_par0:131072,dla_par1:65536,dla_par2:16384`.
"""
import struct
import sys
import pathlib

# name, byte size of the RAM instance
DEFAULT_MEMS = [
    ("dla_par0", 131072),
    ("dla_par1", 65536),
]


def extract(blob_path, total):
    blob = pathlib.Path(blob_path).read_bytes()
    tag = struct.pack("<Q", total)
    hits = []
    start = 0
    while True:
        i = blob.find(tag, start)
        if i < 0:
            break
        start = i + 1
        if i >= 8 and struct.unpack_from("<Q", blob, i - 8)[0] == 1:
            if i + 8 + total <= len(blob):
                hits.append(i)
    if len(hits) != 1:
        raise SystemExit(f"expected exactly 1 candidate, found {len(hits)}")
    i = hits[0]
    payload = blob[i + 8: i + 8 + total]

    # Cross-check the fields that follow, so a format drift is caught loudly.
    p = i + 8 + total
    hdr = struct.unpack_from("<BBIIIIII", blob, p)
    p += 26
    num_config_words = struct.unpack_from("<Q", blob, p)[0]
    p += 8
    fsz, bsz = struct.unpack_from("<QQ", blob, p)
    if hdr[0] != 0:
        raise SystemExit("blob has on-chip parameters enabled")
    if num_config_words * 4 + fsz + bsz != total:
        raise SystemExit(
            f"size cross-check failed: config {num_config_words*4} + filter "
            f"{fsz} + bias/scale {bsz} != {total}")
    return payload, num_config_words * 4, fsz


def write_mif(path, data, nbytes):
    words = nbytes // 8
    padded = data + b"\x00" * (nbytes - len(data))
    with open(path, "w", newline="\n") as f:
        f.write("-- Generated by scripts/make_dla_param_mif.py -- do not edit\n")
        f.write(f"DEPTH = {words};\n")
        f.write("WIDTH = 64;\n")
        f.write("ADDRESS_RADIX = HEX;\n")
        f.write("DATA_RADIX = HEX;\n")
        f.write("CONTENT\nBEGIN\n")
        for w in range(words):
            v = struct.unpack_from("<Q", padded, w * 8)[0]
            f.write(f"{w:x}: {v:016x};\n")
        f.write("END;\n")


def main():
    blob_path, total, outdir = sys.argv[1], int(sys.argv[2]), pathlib.Path(sys.argv[3])
    if len(sys.argv) > 4:
        mems = [(s.split(":")[0], int(s.split(":")[1])) for s in sys.argv[4].split(",")]
    else:
        mems = list(DEFAULT_MEMS)
    outdir.mkdir(parents=True, exist_ok=True)
    payload, cfg_bytes, filt_bytes = extract(blob_path, total)
    print(f"config bytes  = {cfg_bytes}  (config words for CSR 532 = "
          f"{cfg_bytes // 8} -> CONFIG_RANGE_MINUS_TWO = {cfg_bytes // 8 - 2})")
    print(f"filter bytes  = {filt_bytes}")
    print(f"total bytes   = {total}")

    capacity = sum(sz for _, sz in mems)
    if total > capacity:
        raise SystemExit(f"image {total} exceeds RAM capacity {capacity}")

    off = 0
    csum = 0
    for name, size in mems:
        chunk = payload[off:off + size]
        write_mif(outdir / f"{name}.mif", chunk, size)
        print(f"{name}.mif: {size} bytes ({size//8} x 64), image bytes "
              f"{off}..{off + len(chunk) - 1}")
        off += size

    # FNV-1a over the whole image, for the firmware readback check.
    h = 0x811C9DC5
    for b in payload:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    csum = h
    print(f"FNV1a(image) = 0x{csum:08x}")
    (outdir / "image_info.txt").write_text(
        f"total_bytes {total}\nconfig_bytes {cfg_bytes}\n"
        f"filter_bytes {filt_bytes}\n"
        f"config_range_minus_two {cfg_bytes // 8 - 2}\nfnv1a 0x{csum:08x}\n"
        f"word0 0x{struct.unpack_from('<Q', payload, 0)[0]:016x}\n"
        f"word1 0x{struct.unpack_from('<Q', payload, 8)[0]:016x}\n")
    print("wrote", outdir / "image_info.txt")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate the small, checked-in-build ResNet8 model descriptor.

The generator deliberately has no TensorFlow/FlatBuffers dependency.  It uses
the repository's read-only ``tflite_introspect`` parser, reads every constant
from the exact FlatBuffer named by model_manifest.json, and emits a C header.
The header is a build artifact (software/resnet8/generated_model.h); rerun
this script whenever the model is changed.
"""
from __future__ import annotations

import argparse
import hashlib
import math
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE / "tools"))
import tflite_introspect as ti  # noqa: E402


def qmult(real: float) -> tuple[int, int]:
    """TFLite QuantizeMultiplierSingle (integer multiplier, signed shift)."""
    if real == 0.0:
        return 0, 0
    significand, exponent = math.frexp(real)
    q = int(round(significand * (1 << 31)))
    if q == (1 << 31):
        q //= 2
        exponent += 1
    return q, exponent


def c_array(name: str, ctype: str, values: list[int], per: int = 16) -> str:
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per):
        out.append("  " + ", ".join(str(v) for v in values[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def path_from_manifest(manifest: dict, root: Path) -> Path:
    p = Path(manifest["source"])
    if p.exists():
        return p
    # Manifests are portable only by repository-relative identity, not host
    # absolute path.  Match the suffix under this checkout.
    suffix = Path("third_party") / "mlcommons_tiny" / "benchmark" / "training" / "image_classification" / "trained_models" / p.name
    candidate = root / suffix
    if candidate.exists():
        return candidate
    raise FileNotFoundError(manifest["source"])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, default=HERE / "model/model_manifest.json")
    ap.add_argument("--output", type=Path,
                    default=HERE / "software/resnet8/generated_model.h")
    args = ap.parse_args()
    import json
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    model_path = path_from_manifest(manifest, HERE)
    model = model_path.read_bytes()
    if hashlib.sha256(model).hexdigest() != manifest["model"]["sha256"]:
        raise SystemExit("model SHA-256 does not match model_manifest.json")
    parsed = ti.parse_model(model, str(model_path))
    sg = parsed["subgraphs"][0]
    tensors = {t["index"]: t for t in sg["tensors"]}
    buffers = parsed["buffers"]

    def buf(tidx: int) -> bytes:
        bi = tensors[tidx]["buffer"]
        b = buffers[bi]
        off, size = b["data_offset"], b["size"]
        if off is None or size == 0:
            return b""
        return model[off:off + size]

    def i8s(tidx: int) -> list[int]:
        return list(struct.unpack("<%db" % len(buf(tidx)), buf(tidx)))

    def i32s(tidx: int) -> list[int]:
        b = buf(tidx)
        return list(struct.unpack("<%di" % (len(b) // 4), b))

    def q(tidx: int) -> tuple[float, int]:
        z = tensors[tidx]["quantization"]
        return float(z["scale"][0]), int(z["zero_point"][0])

    # Emit each constant once, preserving the FlatBuffer's native layout.
    chunks: list[str] = []
    chunks.append("/* Generated by tools/generate_resnet8_model.py. DO NOT EDIT. */")
    chunks.append("#ifndef RESNET8_GENERATED_MODEL_H")
    chunks.append("#define RESNET8_GENERATED_MODEL_H")
    chunks.append("#include <stdint.h>")
    chunks.append("")
    chunks.append("typedef struct { const int8_t *weights; const int32_t *bias;\n"
                  "  const int32_t *multiplier; const int8_t *shift;\n"
                  "  int input_h, input_w, input_c, output_h, output_w, output_c;\n"
                  "  int kernel_h, kernel_w, stride_h, stride_w;\n"
                  "  int input_zero_point, output_zero_point, fused_relu;\n"
                  "} r8_conv_desc;")
    chunks.append("typedef struct { const int32_t *m1; const int8_t *s1; const int32_t *m2; const int8_t *s2;\n"
                  "  int count, input1_zero_point, input2_zero_point, output_zero_point, fused_relu;\n"
                  "} r8_add_desc;")
    chunks.append("typedef struct { const int8_t *weights; const int32_t *bias; int32_t multiplier; int8_t shift;\n"
                  "  int input_zero_point, output_zero_point, rows, cols; } r8_fc_desc;")

    conv_defs: list[str] = []
    conv_descs: list[str] = []
    add_descs: list[str] = []
    ops = sg["operators"]
    conv_num = add_num = 0
    for op in ops:
        name = op["operator"]
        if name == "CONV_2D":
            inp, wt, bias, out = op["inputs"][0], op["inputs"][1], op["inputs"][2], op["outputs"][0]
            t = tensors[wt]
            ws = t["quantization"]["scale"]
            iscale, izp = q(inp); oscale, ozp = q(out)
            wvals = i8s(wt); bvals = i32s(bias)
            mvals, svals = [], []
            for scale in ws:
                m, s = qmult(iscale * float(scale) / oscale)
                mvals.append(m); svals.append(s)
            tag = f"conv{conv_num}"
            conv_defs += [c_array(f"r8_{tag}_weights", "int8_t", wvals),
                          c_array(f"r8_{tag}_bias", "int32_t", bvals),
                          c_array(f"r8_{tag}_multiplier", "int32_t", mvals),
                          c_array(f"r8_{tag}_shift", "int8_t", svals)]
            ish, isw, isc = tensors[inp]["shape"][1:]
            osh, osw, osc = tensors[out]["shape"][1:]
            opt = op["builtin_options"]
            conv_descs.append(
                "{r8_%s_weights, r8_%s_bias, r8_%s_multiplier, r8_%s_shift, %d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d,%d},"
                % (tag, tag, tag, tag, ish, isw, isc, osh, osw, osc,
                   t["shape"][1], t["shape"][2], opt["stride_h"], opt["stride_w"], izp, ozp,
                   int(opt["fused_activation"]["name"] == "RELU")))
            conv_num += 1
        elif name == "ADD":
            a, b, out = op["inputs"][0], op["inputs"][1], op["outputs"][0]
            ascale, azp = q(a); bscale, bzp = q(b); oscale, ozp = q(out)
            m1, s1 = qmult(ascale / oscale); m2, s2 = qmult(bscale / oscale)
            tag = f"add{add_num}"
            conv_defs += [c_array(f"r8_{tag}_m1", "int32_t", [m1]), c_array(f"r8_{tag}_s1", "int8_t", [s1]),
                          c_array(f"r8_{tag}_m2", "int32_t", [m2]), c_array(f"r8_{tag}_s2", "int8_t", [s2])]
            count = 1
            for x in tensors[out]["shape"]: count *= x
            add_descs.append("{r8_%s_m1, r8_%s_s1, r8_%s_m2, r8_%s_s2, %d,%d,%d,%d,%d}," %
                             (tag, tag, tag, tag, count, azp, bzp, ozp,
                              int(op["builtin_options"]["fused_activation"]["name"] == "RELU")))
            add_num += 1

    chunks.extend(conv_defs)
    chunks.append("static const r8_conv_desc r8_conv[9] = {")
    chunks.extend("  " + x for x in conv_descs)
    chunks.append("};")
    chunks.append("static const r8_add_desc r8_add[3] = {")
    chunks.extend("  " + x for x in add_descs)
    chunks.append("};")

    # FC and softmax are the only remaining constant tensors.
    fc_op = next(o for o in ops if o["operator"] == "FULLY_CONNECTED")
    fi, fw, fb, fo = fc_op["inputs"][0], fc_op["inputs"][1], fc_op["inputs"][2], fc_op["outputs"][0]
    fis, fizp = q(fi); fos, fozp = q(fo)
    fm, fs = qmult(fis * float(tensors[fw]["quantization"]["scale"][0]) / fos)
    chunks += [c_array("r8_fc_weights", "int8_t", i8s(fw)), c_array("r8_fc_bias", "int32_t", i32s(fb))]
    chunks.append("static const r8_fc_desc r8_fc = {r8_fc_weights, r8_fc_bias, %d, %d, %d, %d, %d, %d};" %
                  (fm, fs, fizp, fozp, tensors[fw]["shape"][0], tensors[fw]["shape"][1]))
    # Softmax LUT: exp(-delta * FC output scale), Q15.  It is intentionally
    # generated from the model scale and documented as an integer approximation.
    out_scale, _ = q(fo)
    lut = [int(round(math.exp(-i * out_scale) * 32768.0)) for i in range(256)]
    chunks.append(c_array("r8_softmax_exp_q15", "uint16_t", lut))
    chunks.append(f"#define R8_MODEL_SHA256 \"{hashlib.sha256(model).hexdigest()}\"")
    chunks.append("#define R8_ACTIVATION_SLOT_BYTES 16384")
    chunks.append("#define R8_ACTIVATION_ARENA_BYTES (3 * R8_ACTIVATION_SLOT_BYTES)")
    chunks.append("#endif")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n\n".join(chunks) + "\n", encoding="utf-8", newline="\n")
    print(f"generated {args.output} ({args.output.stat().st_size} bytes) from {model_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
